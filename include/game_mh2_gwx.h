/* MH2: game_w fields by MH1 byte offset, for code that reaches game_w raw (see include/game_mh2.h for what is known) */
#define GWX(o) ((o) >= 0x17 && (o) < 0x34 ? (o) + 2 : \
                (o) == 0xD1 ? 0x3C : (o) == 0xD2 ? 0x3D : (o) == 0xD3 ? 0x3E : (o) == 0xD4 ? 0x3F : (o) == 0xD5 ? 0x40 : \
                (o) == 0x1DC ? 0x41 : (o) == 0x80 ? 0x110 : (o) == 0x81 ? 0x111 : (o) == 0x82 ? 0x112 : (o) == 0x83 ? 0x113 : \
                (o) == 0xCC ? 0x12C : (o) == 0xCE ? 0x12E : (o) == 0xD0 ? 0x130 : (o) == 0x124 ? 0x134 : (o) == 0x128 ? 0x140 : \
                (o) == 0x1A8 ? 0x200 : (o) == 0x1B0 ? 0x20C : (o) == 0x1B2 ? 0x208 : (o) == 0x1B3 ? 0x209 : (o) == 0x1DD ? 0x131 : \
                (o) == 0x1E0 ? 0x20E : (o) == 0x1E8 ? 0x276 : (o) == 0x208 ? 0x224 : (o) == 0x210 ? 0x13C : (o) == 0x211 ? 0x13D : \
                (o) == 0x212 ? 0x13E : (o) == 0x21B ? 0x26E : (o) == 0x21C ? 0x26F : (o) == 0x21D ? 0x13F : (o) == 0x21E ? 0x271 : \
                (o) == 0x21F ? 0x275 : (o))
#endif
