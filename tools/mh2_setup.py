#!/usr/bin/env python3
"""mh2_setup.py - splat inputs for Monster Hunter 2 (Dos), JP 1.04, SLPM_662.80 (docs/mh2.md).

Reads the owner's disc/mh2/SLPM_662.80 and disc/mh2/overlays/*.bin (overlays carved
from DATA.BIN) and writes:

  build/mh2/split/MODULE.bin     the bytes to match (build/ is gitignored)
  config/mh2/MODULE.yaml         splat config: names and addresses only, no game bytes

Function names come from config/mh2/symbols/MODULE.txt (tools/mh2_map.py). Decompiled
code is listed in config/mh2/c_files.txt as `MODULE START END NAME` (NAME relative to
src/) and the asm around each range is cut so the C object drops in its place.

Usage (or simply: tools/mh2_rebuild.sh):
    python3 tools/mh2_setup.py
    .venv/bin/python -m splat split config/mh2/MODULE.yaml
    VERSION=mh2 python3 tools/build.py
"""
import hashlib
import os
import re
import struct
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ELF = os.path.join(ROOT, "disc/mh2/SLPM_662.80")
OVL = os.path.join(ROOT, "disc/mh2/overlays")
OUT = os.path.join(ROOT, "build/mh2/split")

GP = 0x001D05F0           # .reginfo
OVERLAYS = ["sub_main", "select", "game", "lobby", "yn", "plsel", "gm_sub", "lbguild",
            "nethttp", "test", "dnas_net", "dnas_ins"]
MAIN = dict(
    vram=0x00100000,
    file_off=0x280,        # program header 0
    text_end=0x195C00,     # "PsIIlibcdvd" version tag: the first data word
    file_end=0x1C8600,     # FileSiz: exactly gp - 0x7FF0, so all small data is bss
    mem_end=0x2E3900,      # MemSiz; sub_main.bin loads here
)
# Which other modules' symbols an overlay may name. The overlays share load addresses in
# groups (game/lobby/select; gm_sub/lbguild/nethttp; yn/dnas_*), so only the set the game
# really loads together may be listed, or a name lands in the wrong overlay's memory.
LOADED_WITH = {"game": ["gm_sub", "yn"], "gm_sub": ["game", "yn"], "yn": ["game", "gm_sub"],
               "lobby": ["nethttp", "lbguild"], "nethttp": ["lobby"], "lbguild": ["lobby"]}

YAML = """# Generated by tools/mh2_setup.py. Target: byte-identical rebuild of
# {what} from SLPM_662.80 (PS2 Monster Hunter 2, Japan, 1.04).
name: Monster Hunter 2 (JP) {module}
sha1: {sha1}
options:
  basename: {module}
  target_path: build/mh2/split/{module}.bin
  elf_path: build/mh2/{module}.elf
  base_path: ../..
  platform: ps2
  compiler: MWCCPS2
  symbol_addrs_path: [{symfiles}]
  undefined_funcs_auto_path: build/mh2/auto/{module}_undefined_funcs_auto.txt
  undefined_syms_auto_path: build/mh2/auto/{module}_undefined_syms_auto.txt
  asm_path: asm/mh2/{module}
  src_path: src
  asset_path: assets/mh2/{module}
  build_path: build/mh2
  ld_script_path: build/mh2/{module}.ld
  gp_value: 0x{gp:08X}
  find_file_boundaries: False
  emit_subalign: False
  mips_abi_gpr: numeric
  section_order: [".text", ".data", ".rodata", ".sdata", ".bss"]
  string_encoding: ASCII
  data_string_encoding: ASCII
  create_undefined_funcs_auto: True
  create_undefined_syms_auto: True
segments:
  - name: {module}
    type: code
    start: 0x000000
    vram: 0x{vram:08X}
    bss_size: 0x{bss:X}
    subsegments:
{sub}
  - [0x{end:X}]
"""


def c_ranges():
    path = os.path.join(ROOT, "config/mh2/c_files.txt")
    out = []
    if os.path.exists(path):
        for line in open(path):
            f = line.split("#", 1)[0].split()
            if f:
                out.append((f[0], int(f[1], 0), int(f[2], 0), f[3]))
    return out


def text_subsegments(module, vram, lo, hi, ranges):
    cuts = {lo: ("asm", None)}
    for mod, start, end, name in ranges:
        if mod == module:
            cuts[start] = ("c", name)
            if end not in cuts and end < hi:
                cuts[end] = ("asm", None)
    sub = []
    for a in sorted(cuts):
        kind, name = cuts[a]
        if kind == "c":
            sub.append("      - [0x%06X, c, %s]" % (a - vram, name))
        else:
            sub.append("      - [0x%06X, asm, text/%s_%06X]" % (a - vram, module, a))
    return sub


def write(module, what, blob, symfiles, vram, bss, sub):
    os.makedirs(OUT, exist_ok=True)
    os.makedirs(os.path.join(ROOT, "build/mh2/auto"), exist_ok=True)
    os.makedirs(os.path.join(ROOT, "config/mh2/symbols"), exist_ok=True)
    for s in symfiles:
        p = os.path.join(ROOT, "config/mh2/symbols/%s.txt" % s)
        if not os.path.exists(p):
            open(p, "w").close()
    p = os.path.join(OUT, module + ".bin")
    if not os.path.exists(p) or open(p, "rb").read() != blob:
        open(p, "wb").write(blob)
    text = YAML.format(what=what, module=module, sha1=hashlib.sha1(blob).hexdigest(),
                       symfiles=", ".join("config/mh2/symbols/%s.txt" % s for s in symfiles),
                       gp=GP, vram=vram, bss=bss, sub="\n".join(sub), end=len(blob))
    open(os.path.join(ROOT, "config/mh2/%s.yaml" % module), "w").write(text)
    print("%-9s %8d bytes  vram 0x%08X" % (module, len(blob), vram))


def write_aliases():
    """config/mh2/MODULE_aliases.txt, linker PROVIDEs: every name a module can see, the func_ADDRESS form of named
    functions (spimdisasm keeps that form for some .word references), and the names carried C uses (c_aliases.txt)."""
    pat = re.compile(r"^(\S+) = 0x([0-9A-F]+);(.*)")
    names = {}
    for m in ["main"] + OVERLAYS:
        p = os.path.join(ROOT, "config/mh2/symbols/%s.txt" % m)
        if os.path.exists(p):
            for l in open(p):
                r = pat.match(l)
                if r:
                    a = int(r[2], 16)
                    names.setdefault(r[1], (m, a))
                    if "type:func" in r[3]:
                        names.setdefault("func_%08X" % a, (m, a))
    carried = {}
    p = os.path.join(ROOT, "config/mh2/c_aliases.txt")
    if os.path.exists(p):
        for l in open(p):
            f = l.split("#", 1)[0].split()
            if f:
                carried[f[0]] = int(f[1], 16)
    for m in ["main"] + OVERLAYS:
        vis = {"main", "sub_main", m} | set(LOADED_WITH.get(m, []))
        with open(os.path.join(ROOT, "config/mh2/%s_aliases.txt" % m), "w") as fh:
            fh.write("/* Generated by tools/mh2_setup.py: names at MH2 addresses (linker PROVIDEs). */\n")
            for n, (mm, a) in sorted(names.items(), key=lambda x: (x[1][1], x[0])):
                if mm in vis and n not in carried:
                    fh.write("PROVIDE(%s = 0x%08X);\n" % (n, a))
            for n, a in sorted(carried.items()):
                fh.write("PROVIDE(%s = 0x%08X);\n" % (n, a))


def main():
    ranges = c_ranges()
    write_aliases()
    m = MAIN
    elf = open(ELF, "rb").read()
    blob = elf[m["file_off"]:m["file_off"] + m["file_end"] - m["vram"]]
    sub = text_subsegments("main", m["vram"], m["vram"], m["text_end"], ranges)
    sub.append("      - [0x%06X, data, data/main_data]" % (m["text_end"] - m["vram"]))
    write("main", "the main executable's code and data", blob, ["main", "sub_main"], m["vram"],
          m["mem_end"] - m["file_end"], sub)
    for ov in OVERLAYS:
        blob = open(os.path.join(OVL, ov + ".bin"), "rb").read()
        assert blob[:4] == b"MWo3", ov
        load, text, data, bss = struct.unpack_from("<4I", blob, 8)
        assert len(blob) == 0x40 + text + data, ov
        lo, hi = load + 0x40, load + 0x40 + text
        sub = ["      - [0x000000, textbin, header]"]
        sub += text_subsegments(ov, load, lo, hi, ranges)
        if data:
            sub.append("      - [0x%06X, data, data/%s_data]" % (hi - load, ov))
        syms = ["main", "sub_main"] + ([ov] if ov != "sub_main" else [])
        syms += [o for o in LOADED_WITH.get(ov, []) if o not in syms]
        write(ov, "overlay %s.bin (carved from DATA.BIN)" % ov, blob, syms, load, bss, sub)


if __name__ == "__main__":
    main()
