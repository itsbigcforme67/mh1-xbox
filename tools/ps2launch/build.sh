#!/bin/sh
# Build MH1LAUNCH.ELF, the memory-card launcher (src/ps2patch/launcher.c, docs/PLAYING.md), with the open ps2sdk:
#   PS2DEV=~/ps2dev/sdk/ps2dev tools/ps2launch/build.sh        -> build/ps2launch/MH1LAUNCH.ELF
# The ps2sdk toolchain is not in the repo: the prebuilt release from github.com/ps2dev/ps2dev/releases (latest,
# ps2dev-ubuntu-latest.tar.gz) unpacked anywhere; PS2DEV points at its ps2dev/ folder. Needs neither the disc nor the
# PS2 rebuild: the in-game blob (launch_hook.c + online.c) is linked against tools/ps2launch/syms.ld (addresses).
set -e
cd "$(dirname "$0")/../.."
PS2DEV=${PS2DEV:-$HOME/ps2dev/sdk/ps2dev}
PS2SDK=${PS2SDK:-$PS2DEV/ps2sdk}
export PATH="$PS2DEV/ee/bin:$PATH"
CC=mips64r5900el-ps2-elf-gcc
command -v $CC >/dev/null || { echo "no $CC (PS2DEV=$PS2DEV; see the header)"; exit 1; }
O=build/ps2launch; mkdir -p $O

# 1. the in-game blobs, one per game, each linked inside that game's dead ms_net_patch_set with its addresses:
#    MH1 (SLPM-65495) at 0x268800 (room up to 0x26A2E8, syms.ld), G (SLPM-65869) at 0x2130D0 (up to 0x214754,
#    syms_mhg.ld; internet_browser at 0x5A2910, 768 bytes, CRC32 0x9482CFD7). Same C for both.
cat > $O/mh1p_conf.h <<H
/* the launcher fills server / login / password at run time from MH1LAUNCH.CNF */
#define MH1P_CONF { "MH1SERVER000", "mh1-server", "", "", "", "0", "100" }
H
BF="-O2 -G0 -mno-abicalls -fno-pic -ffreestanding -fno-builtin -nostdlib -fno-common -fno-zero-initialized-in-bss \
    -fno-asynchronous-unwind-tables -Wall -Iinclude -I$O -DMH1_ONLINE_PATCH"
blob() {    # blob PREFIX ADDR END SYMS EXTRA_CFLAGS
    P=$1; A=$2; E=$3; SY=$4; X=$5
    $CC $BF $X -Dinternet_browser=mh1l_internet_browser -c src/ps2patch/online.c -o $O/${P}_online.o
    $CC $BF $X -c src/ps2patch/launch_hook.c -o $O/${P}_launch_hook.o
    sed "s/\.blob 0x268800/.blob $A/" tools/ps2launch/blob.ld > $O/${P}_blob.ld
    $CC -nostdlib -Wl,--no-warn-mismatch -Wl,-T,$O/${P}_blob.ld -Wl,-T,$SY \
        -o $O/${P}_blob.elf $O/${P}_launch_hook.o $O/${P}_online.o -Wl,-Map,$O/${P}_blob.map -Wl,-e,mh1l_hook
    mips64r5900el-ps2-elf-objcopy -O binary -j .blob $O/${P}_blob.elf $O/${P}_blob.bin
    python3 - $O $P $A $E <<'PY'
import subprocess, sys
o, p, a, e = sys.argv[1], sys.argv[2], int(sys.argv[3], 0), int(sys.argv[4], 0)
syms = {}
for l in subprocess.check_output(["mips64r5900el-ps2-elf-nm", "%s/%s_blob.elf" % (o, p)], text=True).split("\n"):
    q = l.split()
    if len(q) == 3:
        syms[q[2]] = int(q[0], 16)
b = open("%s/%s_blob.bin" % (o, p), "rb").read()
assert syms["mh1p_conf"] >= a and syms["mh1l_hook"] > a and a + len(b) <= e, "blob layout"
U = p.upper()
with open("%s/%s_blob.h" % (o, p), "w") as f:
    f.write("/* generated by tools/ps2launch/build.sh from launch_hook.c + online.c (our code) */\n")
    f.write("#define %s_BLOB_ADDR 0x%Xu\n#define %s_BLOB_END 0x%Xu\n#define %s_CONF_ADDR 0x%Xu\n#define %s_HOOK_ADDR 0x%Xu\n"
            % (U, a, U, e, U, syms["mh1p_conf"], U, syms["mh1l_hook"]))
    f.write("static const unsigned char %s_blob[%d] = {\n" % (p, len(b)))
    for i in range(0, len(b), 16):
        f.write("    " + ", ".join("0x%02X" % x for x in b[i:i + 16]) + ",\n")
    f.write("};\n")
print("%s blob: %d bytes at 0x%X (room up to 0x%X), conf 0x%X, hook 0x%X, browser 0x%X"
      % (p, len(b), a, e, syms["mh1p_conf"], syms["mh1l_hook"], syms["mh1l_internet_browser"]))
PY
}
blob mh1l 0x268800 0x26A2E8 tools/ps2launch/syms.ld ""
blob mhgl 0x2130D0 0x214754 tools/ps2launch/syms_mhg.ld "-DIB_ADDR=0x5A2910u -DIB_SIZE=768u -DIB_CRC=0x9482CFD7u"

# 2. the launcher, linked high (0x01800000) so that it is not overwritten while it loads the game (0x100000-0xE00000)
sed 's/\.text 0x00100000:/.text 0x01800000:/' $PS2SDK/ee/startup/linkfile > $O/linkfile
grep -q '0x01800000' $O/linkfile || { echo "linkfile: base not found"; exit 1; }
$CC -D_EE -G0 -O2 -Wall -I$PS2SDK/ee/include -I$PS2SDK/common/include -Iinclude -I$O \
    -T$O/linkfile -o $O/MH1LAUNCH.ELF src/ps2patch/launcher.c -L$PS2SDK/ee/lib -Wl,-zmax-page-size=128 \
    -lpatches -ldebug -lcdvd
mips64r5900el-ps2-elf-strip $O/MH1LAUNCH.ELF
ls -l $O/MH1LAUNCH.ELF
