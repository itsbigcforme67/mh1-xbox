#!/usr/bin/env python3
"""gen_rt_meta.py - the per-version address facts the PC runtime needs (src/pc/rt/rt_mem.c,
rt_ver.c), as a generated C file:

    python3 tools/gen_rt_meta.py out.c            # VERSION=mh1 (default) or mhg

MH1 (SLPM_654.95) carries its own symbol table and relocations, so for it the file only
names the version; the runtime reads the ELF as before.
For PS2 Monster Hunter G (VERSION=mhg; SLPM_658.69 is stripped) it holds:
  - the symbols per address space (main + sub_main, game, lobby + nethttp, select) from
    build/mhg/pc/symbols (tools/mhg_pcmeta.py: config/mhg/symbols with sizes);
  - the pointer words of the data (config/mhg/pc_ptrs.txt, tools/mhg_pcmeta.py);
  - a map from MH1 addresses to G addresses through names both versions have, for the
    places in src/pc that still name an MH1 address (rt_va_mh1, RTVA in rt.h).
Only names and addresses; no game bytes. Standard library only.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PAT = re.compile(r"^(\S+) = 0x([0-9A-Fa-f]+);(?: // (.*))?$")


def P(*a):
    return os.path.join(ROOT, *a)


def read_syms(path):
    out = []
    for l in open(path):
        m = PAT.match(l.strip())
        if not m:
            continue
        attrs = m.group(3) or ""
        sz = re.search(r"size:0x([0-9A-Fa-f]+)", attrs)
        out.append((int(m.group(2), 16), int(sz.group(1), 16) if sz else 0, m.group(1), "type:func" in attrs))
    out.sort()
    return out


def c_syms(name, lst):
    o = ["const rt_meta_sym %s[] = {" % name]
    for a, sz, n, f in lst:
        o.append('    { 0x%08X, 0x%X, "%s", %d },' % (a, sz, n, 1 if f else 0))
    o.append("    { 0, 0, 0, 0 }")
    o.append("};")
    o.append("const size_t %s_n = %d;" % (name, len(lst)))
    return o


def c_u32(name, lst):
    o = ["const uint32_t %s[] = {" % name]
    for k in range(0, len(lst), 8):
        o.append("    " + " ".join("0x%X," % v for v in lst[k:k + 8]))
    o.append("    0")
    o.append("};")
    o.append("const size_t %s_n = %d;" % (name, len(lst)))
    return o


def main():
    out_path = sys.argv[1]
    ver = os.environ.get("VERSION", "mh1")
    o = ["/* Generated by tools/gen_rt_meta.py (VERSION=%s). Do not edit. */" % ver,
         "#include <stddef.h>", "#include <stdint.h>",
         "typedef struct { uint32_t va, size; const char *name; int func; } rt_meta_sym;",
         "typedef struct { uint32_t mh1, size, va; } rt_meta_va;"]
    sets = ["main", "game", "lobby", "select"]
    if ver not in ("mhg", "mh2"):
        o += ["const int rt_meta_version = 0;", 'const char rt_meta_elf[] = "SLPM_654.95";',
              "const uint32_t rt_meta_main_data = 0;"]
        o += c_u32("rt_meta_main_lobby", [])
        for s in sets:
            o += c_syms("rt_meta_syms_" + s, []) + c_u32("rt_meta_ptrs_" + s, [])
            o += ["const rt_meta_va rt_meta_va_%s[] = { { 0, 0, 0 } };" % s, "const size_t rt_meta_va_%s_n = 0;" % s]
        open(out_path, "w").write("\n".join(o) + "\n")
        return
    mh2 = ver == "mh2"
    if mh2:     # tools/mh2_pcmeta.py; docs/mh2.md for the data start. main -> lobby words: none known yet (docs/mh2_port.md)
        o += ["const int rt_meta_version = 2;", 'const char rt_meta_elf[] = "SLPM_662.80";',
              "const uint32_t rt_meta_main_data = 0x195C00;"]
        o += c_u32("rt_meta_main_lobby", [])
    else:
        o += ["const int rt_meta_version = 1;", 'const char rt_meta_elf[] = "SLPM_658.69";',
              "const uint32_t rt_meta_main_data = 0x253D20;     /* tools/setup_split.py G_MAIN data_start */"]
        ml = [int(l.split()[0], 16) for l in open(P("config/mhg/pc_main_lobby.txt")) if l.strip() and not l.startswith("#")]
        o += c_u32("rt_meta_main_lobby", sorted(set(ml)))     # main data words that point into lobby.bin (tools/mhg_main_lobby.py)
    view = {s: read_syms(P("build/%s/pc/symbols/%s.txt" % (ver, s))) for s in sets}
    ptrs = {}
    cur = None
    for l in open(P("build/mh2/pc/ptrs.txt" if mh2 else "config/mhg/pc_ptrs.txt")):
        l = l.strip()
        if not l or l.startswith("#"):
            continue
        if l.startswith("["):
            cur = l[1:].split("]")[0]
            ptrs.setdefault(cur, [])
            continue
        ptrs[cur].append(int(l, 16))
    pset = {"main": ptrs["main"] + ptrs["sub_main"], "game": ptrs["game"] + ptrs.get("gm_sub", []),
            "lobby": ptrs["lobby"] + ptrs["nethttp"] + ptrs.get("lbguild", []), "select": ptrs["select"]}
    for s in sets:
        o += c_syms("rt_meta_syms_" + s, view[s]) + c_u32("rt_meta_ptrs_" + s, sorted(pset[s]))
    # MH1 address -> G address, by name (main and game together: one address space)
    mh1 = {s: read_syms(P("config/symbols/%s.txt" % s)) for s in sets}
    vsets = {"main": (["main", "game"], ["main", "game"]), "lobby": (["lobby"], ["lobby"]),
             "select": (["select"], ["select"]), "game": ([], [])}
    for s in sets:
        src, dst = vsets[s]
        gname = {}
        for d in dst:
            for a, sz, n, f in view[d]:
                gname.setdefault(n, a)
        rows = []
        for m in src:
            for a, sz, n, f in mh1[m]:
                if n in gname:
                    rows.append((a, sz, gname[n]))
        rows.sort()
        o.append("const rt_meta_va rt_meta_va_%s[] = {" % s)
        for a, sz, g in rows:
            o.append("    { 0x%08X, 0x%X, 0x%08X }," % (a, sz, g))
        o += ["    { 0, 0, 0 }", "};", "const size_t rt_meta_va_%s_n = %d;" % (s, len(rows))]
    open(out_path, "w").write("\n".join(o) + "\n")


if __name__ == "__main__":
    main()
