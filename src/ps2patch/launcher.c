#include "mhgl_blob.h"      /* the same for Monster Hunter G: mhgl_blob[], MHGL_* */

#define VERSION "MH1LAUNCH 1.0"

/* where one game's patch goes (main, the executable's own addresses; every word checked before it is changed) */
typedef struct Patch {
    unsigned dnas_call, dnas_word;      /* ms_network_bb_authentication: its jal InetDNAS2ConnectNetStart */
    unsigned ovl_call, ovl_word;        /* Load_overlay: its jal PatchExecCS */
    unsigned dead, dead_word, dead_end; /* ms_net_patch_set: its first instruction (addiu sp,sp,-N) and its end */
    unsigned blob_addr, conf_addr, hook_addr;
    const unsigned char *blob;
    unsigned blob_size;
} Patch;

typedef struct Game {
    const char *boot;       /* the BOOT2 file name on the disc */
    const char *title;
    unsigned size, crc;     /* the executable: size and CRC32 (tools/disc_files.py) */
    const Patch *patch;     /* NULL: known, no patch yet -> started untouched */
} Game;

static const Patch PATCH_MH1 = {
    0x26827C, 0x0C29DA70u,  /* jal InetDNAS2ConnectNetStart (0xA769C0) */
    0x23E5EC, 0x0C0A31F4u,  /* jal PatchExecCS (0x28C7D0) */
    0x2687E0, 0x27BDFFD0u, 0x26A2E8,
    MH1L_BLOB_ADDR, MH1L_CONF_ADDR, MH1L_HOOK_ADDR, mh1l_blob, sizeof mh1l_blob
};
/* Monster Hunter G: the same three places (docs/network.md "G online"), G's addresses: ms_network_bb_authentication
 * 0x212940 (DNAS call at 0x212B7C), Load_overlay 0x1F17F0 (PatchExecCS 0x237960 called at 0x1F198C),
 * ms_net_patch_set 0x2130B0-0x214754 (only lbc_login_patch calls it, when a server sends a patch) */
static const Patch PATCH_MHG = {
    0x212B7C, 0x0C29DA7Cu,  /* jal InetDNAS2ConnectNetStart (0xA769F0 in G's dnas_net overlay) */
    0x1F198C, 0x0C08DE58u,  /* jal PatchExecCS (0x237960) */
    0x2130B0, 0x27BDFFA0u, 0x214754,
    MHGL_BLOB_ADDR, MHGL_CONF_ADDR, MHGL_HOOK_ADDR, mhgl_blob, sizeof mhgl_blob
};

static const Game GAMES[] = {
    { "SLPM_654.95", "Monster Hunter (Japan)", 5648908u, 0xCF1A62C0u, &PATCH_MH1 },
    { "SLPM_658.69", "Monster Hunter G (Japan)", 2029336u, 0xB25E8415u, &PATCH_MHG },
};

static const char *DENY_IP[] = { "34.75.107.68", "151.80.238.99", "151.80.238.101", "151.80.238.104" };
static const char *DENY_NAME[] = { "mholdschool.com", "capcom.co.jp", "kddi-mmbb.jp", "dnas.playstation.org" };

static MH1PCONF conf;
static char conf_path[256];
static int force_passthrough;

static void say(const char *fmt, const char *a)
{
    char b[256];
    snprintf(b, sizeof b, fmt, a ? a : "");
    scr_printf("%s\n", b);
    printf("MH1LAUNCH: %s\n", b);
}

static void pause_s(int s)
{
    sleep(s);
}

static unsigned crc32_buf(unsigned c, const unsigned char *p, unsigned n)
{
    static unsigned t[256];
    unsigned i, k;
    if (!t[1])
        for (i = 0; i < 256; i++) {
            unsigned v = i;
            for (k = 0; k < 8; k++)
                v = (v >> 1) ^ (0xEDB88320u & -(v & 1));
            t[i] = v;
        }
    c = ~c;
    while (n--)
        c = t[(c ^ *p++) & 0xFF] ^ (c >> 8);
    return ~c;
}

static void reset_iop(void)
{
    SifInitRpc(0);
    while (!SifIopReset("", 0))
        ;
    while (!SifIopSync())
        ;
    SifInitRpc(0);
    SifInitIopHeap();
    SifLoadFileInit();
    sbv_patch_enable_lmb();
    sbv_patch_disable_prefix_check();
}

static void load_modules(void)
{
    SifLoadModule("rom0:SIO2MAN", 0, NULL);
    SifLoadModule("rom0:MCMAN", 0, NULL);
    SifLoadModule("rom0:MCSERV", 0, NULL);
}

/* ------------------------------------------------------------------ config */
static void trim(char *s)
{
    char *e;
    while (*s == ' ' || *s == '\t')
        memmove(s, s + 1, strlen(s));
    e = s + strlen(s);
    while (e > s && (e[-1] == ' ' || e[-1] == '\t' || e[-1] == '\r' || e[-1] == '\n'))
        *--e = 0;
}

static int read_conf_file(const char *path)
{
    FILE *f = fopen(path, "r");
    char line[160];
    if (!f)
        return 0;
    while (fgets(line, sizeof line, f)) {
        char *eq = strchr(line, '=');
        if (line[0] == '#' || line[0] == ';' || !eq)
            continue;
        *eq = 0;
        trim(line);
        trim(eq + 1);
        if (!strcmp(line, "server"))
            strncpy(conf.server, eq + 1, sizeof conf.server - 1);
        else if (!strcmp(line, "login"))
            strncpy(conf.login, eq + 1, sizeof conf.login - 1);
        else if (!strcmp(line, "password"))
            strncpy(conf.password, eq + 1, sizeof conf.password - 1);
        else if (!strcmp(line, "name"))
            strncpy(conf.name, eq + 1, sizeof conf.name - 1);
        else if (!strcmp(line, "test_force_passthrough"))     /* tests only: treat every disc as unknown */
            force_passthrough = atoi(eq + 1);
    }
    fclose(f);
    snprintf(conf_path, sizeof conf_path, "%s", path);
    return 1;
}

static int read_conf(const char *argv0)
{
    char p[256];
    const char *fixed[] = { "mc0:/MH1LAUNCH/MH1LAUNCH.CNF", "mc1:/MH1LAUNCH/MH1LAUNCH.CNF" };
    unsigned i;
    memset(&conf, 0, sizeof conf);
    strcpy(conf.id, "MH1SERVER000");
    strcpy(conf.name, "mh1-server");
    strcpy(conf.users, "0");
    strcpy(conf.users_max, "100");
    if (argv0 && *argv0) {      /* next to the ELF: mc0:/APPS/MH1LAUNCH.ELF -> mc0:/APPS/MH1LAUNCH.CNF */
        char *s;
        snprintf(p, sizeof p, "%s", argv0);
        s = strrchr(p, '/');
        if (!s)
            s = strrchr(p, '\\');
        if (!s)
            s = strchr(p, ':');
        if (s) {
            s[1] = 0;
            strncat(p, "MH1LAUNCH.CNF", sizeof p - strlen(p) - 1);
            if (read_conf_file(p))
                return 1;
        }
    }
    for (i = 0; i < sizeof fixed / sizeof fixed[0]; i++)
        if (read_conf_file(fixed[i]))
            return 1;
    return 0;
}

static int conf_ok(void)
{
    char host[0x40], *c;
    unsigned i, n;
    if (!conf.server[0] || !(c = strrchr(conf.server, ':')) || atoi(c + 1) <= 0 || atoi(c + 1) > 65535) {
        say("config: 'server = HOST:PORT' is missing or wrong", NULL);
        return 0;
    }
    snprintf(host, sizeof host, "%.*s", (int)(c - conf.server), conf.server);
    for (i = 0; host[i]; i++)
        if (host[i] >= 'A' && host[i] <= 'Z')
            host[i] += 32;
    for (i = 0; i < sizeof DENY_IP / sizeof DENY_IP[0]; i++)
        if (!strcmp(host, DENY_IP[i])) {
            say("config: %s is MH Oldschool's server; this launcher is for your own server only", host);
            return 0;
        }
    for (i = 0; i < sizeof DENY_NAME / sizeof DENY_NAME[0]; i++)
        if (strstr(host, DENY_NAME[i])) {
            say("config: %s is not allowed; this launcher is for your own server only", host);
            return 0;
        }
    n = strlen(conf.login);
    for (i = 0; i < n; i++)
        if (conf.login[i] < '0' || conf.login[i] > '9')
            break;
    if (n < 8 || n > 10 || i != n) {
        say("config: 'login' must be your account's 8-10 digits", NULL);
        return 0;
    }
    if (!conf.password[0] || strlen(conf.password) > 16) {
        say("config: 'password' must be your account's password (16 characters)", NULL);
        return 0;
    }
    return 1;
}

/* ------------------------------------------------------------------ the disc */
static int read_system_cnf(char *boot, int n)
{
    FILE *f = fopen("cdrom0:\\SYSTEM.CNF;1", "r");
    char line[160];
    boot[0] = 0;
    if (!f)
        return 0;
    while (fgets(line, sizeof line, f)) {
        char *eq = strchr(line, '=');
        if (!eq)
            continue;
        *eq = 0;
        trim(line);
        trim(eq + 1);
        if (!strcmp(line, "BOOT2"))
            snprintf(boot, n, "%s", eq + 1);
    }
    fclose(f);
    return boot[0] != 0;
}

/* the BOOT2 path "cdrom0:\SLPM_654.95;1" -> "SLPM_654.95" */
static void boot_id(const char *path, char *id, int n)
{
    const char *s = strrchr(path, '\\');
    const char *e;
    s = s ? s + 1 : strchr(path, ':') ? strchr(path, ':') + 1 : path;
    e = strchr(s, ';');
    snprintf(id, n, "%.*s", e ? (int)(e - s) : (int)strlen(s), s);
}

static char boot_path[160];
static unsigned char *elf;
static unsigned elf_size;

static void start_untouched(void)
{
    char *args[1];
    args[0] = boot_path;
    say("starting %s as the console would", boot_path);
    pause_s(1);
    SifExitRpc();
    LoadExecPS2("rom0:PS2LOGO", 1, args);
}

static void back_to_browser(void)
{
    say("no PS2 game disc: back to the browser", NULL);
    pause_s(2);
    SifExitRpc();
    Exit(0);
}

/* reads the whole executable (no seek: the size comes from GAMES[]; one byte more proves the end) */
static int load_elf_file(const char *path, unsigned size)
{
    FILE *f = fopen(path, "rb");
    unsigned n = 0;
    size_t r;
    if (!f)
        return 0;
    if (!(elf = malloc(size + 0x8000))) {
        fclose(f);
        return 0;
    }
    while ((r = fread(elf + n, 1, n + 0x8000 > size + 0x8000 ? size + 0x8000 - n : 0x8000, f)) > 0 && n < size + 1)
        n += r;
    fclose(f);
    elf_size = n;
    printf("MH1LAUNCH: read %u bytes\n", n);
    return n == size;
}

static unsigned rd32(const unsigned char *p)
{
    return p[0] | p[1] << 8 | p[2] << 16 | (unsigned)p[3] << 24;
}

/* ------------------------------------------------------------------ the patch (MH1 or G) */
#define W(a) (*(volatile unsigned *)(a))
static int patch_game(const Patch *p)
{
    unsigned i;
    if (!conf_ok())
        return 0;
    /* the original words first: any difference -> untouched */
    if (W(p->dnas_call) != p->dnas_word || W(p->ovl_call) != p->ovl_word || W(p->dead) != p->dead_word) {
        say("unexpected code in the executable: not patched", NULL);
        return 0;
    }
    if (p->blob_addr + p->blob_size > p->dead_end || p->blob_addr < p->dead + 8) {
        say("internal: the blob does not fit", NULL);
        return 0;
    }
    W(p->dnas_call) = 0x24020001u;                  /* addiu v0, zero, 1: DNAS "authenticated" */
    W(p->dead) = 0x03E00008u;                       /* jr ra */
    W(p->dead + 4) = 0x24020001u;                   /* addiu v0, zero, 1 (ms_net_patch_set: done) */
    for (i = p->dead + 8; i < p->blob_addr; i += 4)
        W(i) = 0;
    memcpy((void *)p->blob_addr, p->blob, p->blob_size);
    memcpy((void *)p->conf_addr, &conf, sizeof conf);
    W(p->ovl_call) = 0x0C000000u | ((p->hook_addr >> 2) & 0x03FFFFFFu);  /* jal mh1l_hook */
    printf("MH1LAUNCH: patched: DNAS skip, lobby hook, server %s login %s\n", conf.server, conf.login);
    return 1;
}

static void boot_patched(const Game *g)
{
    unsigned phoff, phnum, entry, i;
    char *args[1];
    if (!conf_path[0]) {
        say("no MH1LAUNCH.CNF (server, login, password): starting the game unpatched", NULL);
        pause_s(3);
        start_untouched();
        return;
    }
    say("reading %s from the disc ...", g->boot);
    if (!load_elf_file(boot_path, g->size) || elf_size != g->size || crc32_buf(0, elf, elf_size) != g->crc) {
        say("this disc's executable is not the expected one: starting it untouched", NULL);
        pause_s(3);
        start_untouched();
        return;
    }
    entry = rd32(elf + 24);
    phoff = rd32(elf + 28);
    phnum = elf[44] | elf[45] << 8;
    for (i = 0; i < phnum; i++) {       /* load the PT_LOAD segments, clear the rest of each */
        const unsigned char *ph = elf + phoff + i * 32;
        unsigned off = rd32(ph + 4), va = rd32(ph + 8), fs = rd32(ph + 16), ms = rd32(ph + 20);
        if (rd32(ph) != 1)
            continue;
        if (fs)
            memcpy((void *)va, elf + off, fs);
        if (ms > fs)
            memset((void *)(va + fs), 0, ms - fs);
    }
    if (!patch_game(g->patch)) {
        say("starting the game untouched", NULL);
        pause_s(3);
        start_untouched();
        return;
    }
    say("%s: online patch in RAM", g->title);
    say("server %s", conf.server);
    pause_s(1);
    FlushCache(0);
    FlushCache(2);
    args[0] = boot_path;
    reset_iop();
    SifExitRpc();
    ExecPS2((void *)entry, NULL, 1, args);
}

int main(int argc, char *argv[])
{
    char id[32];
    int type, t;
    unsigned i;
    init_scr();
    say(VERSION " - Monster Hunter online launcher (our own server; docs/PLAYING.md)", NULL);
    reset_iop();
    load_modules();
    if (read_conf(argc > 0 ? argv[0] : NULL))
        say("config: %s", conf_path);
    sceCdInit(SCECdINoD);
    for (t = 0; t < 100 && sceCdDiskReady(1) != SCECdComplete; t++)
        usleep(100000);
    type = sceCdGetDiskType();
    if (type != SCECdPS2CD && type != SCECdPS2CDDA && type != SCECdPS2DVD) {
        back_to_browser();
        return 0;
    }
    if (!read_system_cnf(boot_path, sizeof boot_path)) {
        back_to_browser();
        return 0;
    }
    boot_id(boot_path, id, sizeof id);
    say("disc: %s", id);
    for (i = 0; i < sizeof GAMES / sizeof GAMES[0] && !force_passthrough; i++)
        if (!strcmp(id, GAMES[i].boot)) {
            if (!GAMES[i].patch) {
                say("%s: no online patch for this game yet", GAMES[i].title);
                break;
            }
            boot_patched(&GAMES[i]);
            break;
        }
    start_untouched();
    return 0;
}
