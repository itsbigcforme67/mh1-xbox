/* src/ps2patch/launcher.c - MH1LAUNCH.ELF, the memory-card launcher for real PS2s (docs/network.md 3.8,
 * docs/PLAYING.md "Playing online on a real PS2 without burning a disc"). Our own code, built with the open ps2sdk
 * (tools/ps2launch/build.sh). No game bytes are in it: it only reads the player's own disc.
 *
 * Safe to auto-run at every power-on (Free McBoot / OpenTuna "auto launch"):
 *   - no disc, or not a PS2 game (PS1, DVD video, audio CD): back to the console's browser, nothing touched;
 *   - a PS2 game that is not in GAMES[] below, or a known game without a patch, or a disc whose
 *     executable is not byte for byte the expected one: started as the console would (rom0:PS2LOGO with the disc's
 *     BOOT2 file), untouched;
 *   - Monster Hunter (Japan) SLPM-65495 or Monster Hunter G (Japan) SLPM-65869 with a config file: its executable is
 *     loaded from the disc into RAM, patched there (below), and started. The disc and the memory card are not written.
 *     G's patch is the same three changes at G's addresses (PATCH_MHG below; its blob is linked with G's symbols).
 *
 * The RAM patch (the same effect as tools/ps2_patch.py's patched image, made at run time; no DNAS crypto of any kind):
 *   1. ms_network_bb_authentication (0x268040): its call of InetDNAS2ConnectNetStart at 0x26827C becomes "v0 = 1"
 *      (authenticated), so the success path runs as before (Sony's DNAS servers are gone);
 *   2. ms_net_patch_set (0x2687E0, the dead "patch download" menu; our server sends no patches) becomes "return 1",
 *      and its body from 0x268800 holds our blob: launch_hook.c + online.c (mh1l_internet_browser, the server table
 *      fill) + the player's settings (MH1PCONF from the config file);
 *   3. Load_overlay's call of PatchExecCS at 0x23E5EC calls mh1l_hook instead, which calls PatchExecCS and then
 *      points the lobby's internet_browser (the dead KDDI portal) at mh1l_internet_browser each time lobby.bin loads.
 * Every patched word is checked against the expected original instruction first (and the whole executable against
 * its size and CRC32); any difference -> the game is started untouched.
 *
 * Config file MH1LAUNCH.CNF (plain text, next to the ELF, or mc0:/MH1LAUNCH/, mc1:/MH1LAUNCH/):
 *     server = 192.168.1.20:10200      (our mh1-server: tools/server, docs/server.md; a name or an address)
 *     login = 12345678                 (the account's 8-10 digits)
 *     password = ABCDEFGH12345678      (its 16 characters)
 * MH Oldschool's servers are refused (as tools/ps2_patch.py does): this launcher is for our own server only. */
